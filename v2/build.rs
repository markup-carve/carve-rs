//! Generates the typed AST and the rule tables from the specification data in
//! `spec-data/` (a verbatim copy of `spec/0.2/data/` of the carve repository).
//! Nothing in `src/` copies a value from those files by hand.

use serde_json::{Map, Value};
use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_default()).join("spec-data");
    println!("cargo:rerun-if-changed=spec-data");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_default());
    let ast = gen_ast(&load(&dir, "ast-schema.json"), &load(&dir, "node-slots.json"));
    write(&out.join("ast_gen.rs"), &ast);
    write(&out.join("tables_gen.rs"), &gen_tables(&dir));
}

fn load(dir: &Path, name: &str) -> Value {
    let text = fs::read_to_string(dir.join(name)).unwrap_or_else(|e| panic!("read {name}: {e}"));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {name}: {e}"))
}

fn write(path: &Path, text: &str) {
    fs::write(path, text).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
}

fn camel(name: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for c in name.chars() {
        if c.is_ascii_alphanumeric() {
            if up {
                out.extend(c.to_uppercase());
            } else {
                out.push(c);
            }
            up = false;
        } else {
            up = true;
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    out
}

fn snake(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars() {
        if c.is_ascii_uppercase() {
            out.push('_');
            out.push(c.to_ascii_lowercase());
        } else if c == '.' || c == '-' {
            out.push('_');
        } else {
            out.push(c);
        }
    }
    out
}

const COMMON: [&str; 8] = ["type", "attrs", "data", "pos", "segments", "metadata", "dir", "lang"];

enum FieldKind {
    Nodes,
    NodeBox,
    Str,
    Int,
    Num,
    Bool,
    Enum(Vec<String>),
    Strings,
    Json,
    Marker,
    Task,
}

fn is_node_list(p: &Value) -> bool {
    let Some(items) = p.get("items") else { return false };
    if let Some(r) = items.get("$ref").and_then(Value::as_str) {
        return r.starts_with("#/$defs/");
    }
    items
        .get("oneOf")
        .and_then(Value::as_array)
        .is_some_and(|a| a.iter().all(|x| x.get("$ref").and_then(Value::as_str).is_some_and(|r| r.starts_with("#/$defs/"))))
}

fn field_kind(name: &str, p: &Value) -> FieldKind {
    if name == "marker" {
        return FieldKind::Marker;
    }
    if name == "task" {
        return FieldKind::Task;
    }
    if p.get("$ref").and_then(Value::as_str).is_some_and(|r| r.starts_with("#/$defs/")) {
        return FieldKind::NodeBox;
    }
    if let Some(values) = p.get("enum").and_then(Value::as_array) {
        return FieldKind::Enum(values.iter().filter_map(|v| v.as_str().map(String::from)).collect());
    }
    if let Some(c) = p.get("const") {
        return if c.is_boolean() { FieldKind::Bool } else { FieldKind::Str };
    }
    match p.get("type").and_then(Value::as_str) {
        Some("array") if is_node_list(p) => FieldKind::Nodes,
        Some("array") => {
            let items = p.get("items").cloned().unwrap_or(Value::Null);
            let scalar = items.get("type").and_then(Value::as_str) == Some("string") || items.get("enum").is_some();
            if scalar { FieldKind::Strings } else { FieldKind::Json }
        }
        Some("string") => FieldKind::Str,
        Some("integer") => FieldKind::Int,
        Some("number") => FieldKind::Num,
        Some("boolean") => FieldKind::Bool,
        _ => FieldKind::Json,
    }
}

struct Field {
    json: String,
    rust: String,
    ty: String,
    required: bool,
    kind: FieldKind,
}

fn rust_ident(name: &str) -> String {
    let s = snake(name);
    match s.as_str() {
        "type" | "box" | "ref" | "match" | "mod" | "use" | "where" => format!("r#{s}"),
        _ => s,
    }
}

fn gen_ast(schema: &Value, slots: &Value) -> String {
    let defs = schema.get("$defs").and_then(Value::as_object).cloned().unwrap_or_default();
    let mut out = String::from("// @generated by build.rs from spec-data/ast-schema.json and node-slots.json.\n\n");
    let mut enums = String::new();
    let mut variants = Vec::new();
    for (name, def) in &defs {
        let ty = camel(name);
        variants.push((name.clone(), ty.clone()));
        let props = def.get("properties").and_then(Value::as_object).cloned().unwrap_or_default();
        let required: BTreeSet<String> = def
            .get("required")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(|v| v.as_str().map(String::from)).collect())
            .unwrap_or_default();
        let fields = collect_fields(&ty, &props, &required, &mut enums);
        write_struct(&mut out, name, &ty, &fields);
    }
    out.push_str(&enums);
    write_node_enum(&mut out, &variants);
    write_slots(&mut out, &defs, slots);
    out
}

fn collect_fields(ty: &str, props: &Map<String, Value>, required: &BTreeSet<String>, enums: &mut String) -> Vec<Field> {
    let mut fields = Vec::new();
    for (pname, p) in props {
        if pname == "type" {
            continue;
        }
        let common = COMMON.contains(&pname.as_str());
        let kind = if common { common_kind(pname) } else { field_kind(pname, p) };
        let req = required.contains(pname);
        let base = match &kind {
            FieldKind::Nodes => "Vec<Node>".to_string(),
            FieldKind::NodeBox => "Box<Node>".to_string(),
            FieldKind::Str => "String".to_string(),
            FieldKind::Int => "i64".to_string(),
            FieldKind::Num => "f64".to_string(),
            FieldKind::Bool => "bool".to_string(),
            FieldKind::Strings => "Vec<String>".to_string(),
            FieldKind::Json => common_type(pname),
            FieldKind::Marker => "crate::ast::Marker".to_string(),
            FieldKind::Task => "crate::ast::Task".to_string(),
            FieldKind::Enum(values) => {
                let ename = format!("{ty}{}", camel(pname));
                write_enum(enums, &ename, values);
                ename
            }
        };
        let ty = if req { base } else { format!("Option<{base}>") };
        fields.push(Field { json: pname.clone(), rust: rust_ident(pname), ty, required: req, kind });
    }
    fields
}

fn common_kind(name: &str) -> FieldKind {
    match name {
        "dir" | "lang" => FieldKind::Str,
        _ => FieldKind::Json,
    }
}

fn common_type(name: &str) -> String {
    match name {
        "attrs" => "crate::ast::Attrs".into(),
        "pos" => "crate::ast::Pos".into(),
        "segments" => "Vec<crate::ast::Pos>".into(),
        _ => "serde_json::Value".into(),
    }
}

fn write_enum(out: &mut String, name: &str, values: &[String]) {
    let _ = writeln!(out, "#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]\npub enum {name} {{");
    for (i, v) in values.iter().enumerate() {
        let default = if i == 0 { "#[default]\n    " } else { "" };
        let _ = writeln!(out, "    {default}#[serde(rename = {v:?})]\n    {},", camel(v));
    }
    let _ = writeln!(out, "}}\n\nimpl {name} {{\n    #[must_use]\n    pub const fn as_str(self) -> &'static str {{\n        match self {{");
    for v in values {
        let _ = writeln!(out, "            Self::{} => {v:?},", camel(v));
    }
    let _ = writeln!(out, "        }}\n    }}\n}}\n");
}

fn write_struct(out: &mut String, name: &str, ty: &str, fields: &[Field]) {
    let _ = writeln!(out, "/// The `{name}` node.\n#[derive(Debug, Clone, Default, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct {ty} {{");
    for f in fields {
        let mut attrs = Vec::new();
        if f.json != f.rust.trim_start_matches("r#") {
            attrs.push(format!("rename = {:?}", f.json));
        }
        if !f.required {
            attrs.push("default".into());
            attrs.push("skip_serializing_if = \"Option::is_none\"".into());
        } else if matches!(f.kind, FieldKind::Nodes) {
            attrs.push("default".into());
        }
        if !attrs.is_empty() {
            let _ = writeln!(out, "    #[serde({})]", attrs.join(", "));
        }
        let _ = writeln!(out, "    pub {}: {},", f.rust, f.ty);
    }
    let _ = writeln!(out, "}}\n");
    let _ = (ty, name);
}

fn write_node_enum(out: &mut String, variants: &[(String, String)]) {
    out.push_str("/// Every node type of the 2.0 contract (C2-A-050).\n#[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(tag = \"type\")]\npub enum Node {\n");
    for (json, ty) in variants {
        let _ = writeln!(out, "    #[serde(rename = {json:?})]\n    {ty}({ty}),");
    }
    out.push_str("}\n\nimpl Node {\n    /// The node type name as the schema spells it.\n    #[must_use]\n    pub const fn type_name(&self) -> &'static str {\n        match self {\n");
    for (json, ty) in variants {
        let _ = writeln!(out, "            Self::{ty}(_) => {json:?},");
    }
    out.push_str("        }\n    }\n}\n\n");
}

/// Accessors for the common fields and the walk over node-bearing slots, in the
/// order of node-slots.json (C2-A-025).
fn write_slots(out: &mut String, defs: &Map<String, Value>, slots: &Value) {
    let slot_map = slots.get("nodes").and_then(Value::as_object).cloned().unwrap_or_default();
    let mut pos_arms = String::new();
    let mut pos_mut_arms = String::new();
    let mut attrs_arms = String::new();
    let mut attrs_mut_arms = String::new();
    let mut children_arms = String::new();
    let mut children_mut_arms = String::new();
    let mut walk_arms = String::new();
    let mut walk_mut_arms = String::new();
    for (name, def) in defs {
        let ty = camel(name);
        let props = def.get("properties").and_then(Value::as_object).cloned().unwrap_or_default();
        if props.contains_key("pos") {
            let _ = writeln!(pos_arms, "            Self::{ty}(n) => n.pos.as_ref(),");
            let _ = writeln!(pos_mut_arms, "            Self::{ty}(n) => Some(&mut n.pos),");
        }
        if props.contains_key("attrs") {
            let _ = writeln!(attrs_arms, "            Self::{ty}(n) => n.attrs.as_ref(),");
            let _ = writeln!(attrs_mut_arms, "            Self::{ty}(n) => Some(&mut n.attrs),");
        }
        if props.get("children").is_some_and(is_node_list) {
            let _ = writeln!(children_arms, "            Self::{ty}(n) => Some(&n.children),");
            let _ = writeln!(children_mut_arms, "            Self::{ty}(n) => Some(&mut n.children),");
        }
        let order: Vec<String> = slot_map
            .get(name)
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(|v| v.as_str().map(String::from)).collect())
            .unwrap_or_default();
        let required: BTreeSet<String> = def
            .get("required")
            .and_then(Value::as_array)
            .map(|a| a.iter().filter_map(|v| v.as_str().map(String::from)).collect())
            .unwrap_or_default();
        let mut body = String::new();
        let mut body_mut = String::new();
        for slot in &order {
            let Some(p) = props.get(slot) else { continue };
            let field = rust_ident(slot);
            let req = required.contains(slot);
            match field_kind(slot, p) {
                FieldKind::Nodes if req => {
                    let _ = writeln!(body, "                for c in &n.{field} {{ f(c); }}");
                    let _ = writeln!(body_mut, "                for c in &mut n.{field} {{ f(c); }}");
                }
                FieldKind::Nodes => {
                    let _ = writeln!(body, "                for c in n.{field}.iter().flatten() {{ f(c); }}");
                    let _ = writeln!(body_mut, "                for c in n.{field}.iter_mut().flatten() {{ f(c); }}");
                }
                FieldKind::NodeBox => {
                    let _ = writeln!(body, "                if let Some(c) = &n.{field} {{ f(c); }}");
                    let _ = writeln!(body_mut, "                if let Some(c) = &mut n.{field} {{ f(c); }}");
                }
                _ => {}
            }
        }
        if !body.is_empty() {
            let _ = writeln!(walk_arms, "            Self::{ty}(n) => {{\n{body}            }}");
            let _ = writeln!(walk_mut_arms, "            Self::{ty}(n) => {{\n{body_mut}            }}");
        }
    }
    let _ = write!(
        out,
        "#[allow(unreachable_patterns)]
impl Node {{
    /// The source position, when the node carries one.
    #[must_use]
    pub fn pos(&self) -> Option<&crate::ast::Pos> {{
        match self {{
{pos_arms}            _ => None,
        }}
    }}

    /// The position slot of the node type, when it has one.
    pub fn pos_slot(&mut self) -> Option<&mut Option<crate::ast::Pos>> {{
        match self {{
{pos_mut_arms}            _ => None,
        }}
    }}

    /// The authored attributes, when the node carries them.
    #[must_use]
    pub fn attrs(&self) -> Option<&crate::ast::Attrs> {{
        match self {{
{attrs_arms}            _ => None,
        }}
    }}

    /// The attribute slot of the node type, when it has one.
    pub fn attrs_slot(&mut self) -> Option<&mut Option<crate::ast::Attrs>> {{
        match self {{
{attrs_mut_arms}            _ => None,
        }}
    }}

    /// The primary `children` slot (C2-A-022).
    #[must_use]
    pub fn children(&self) -> Option<&Vec<Node>> {{
        match self {{
{children_arms}            _ => None,
        }}
    }}

    /// The primary `children` slot, mutable.
    pub fn children_mut(&mut self) -> Option<&mut Vec<Node>> {{
        match self {{
{children_mut_arms}            _ => None,
        }}
    }}

    /// Visits every node held in a node-bearing slot, in node-slots.json order.
    pub fn for_each_child(&self, f: &mut dyn FnMut(&Node)) {{
        match self {{
{walk_arms}            _ => {{}}
        }}
    }}

    /// Visits every node held in a node-bearing slot, mutable.
    pub fn for_each_child_mut(&mut self, f: &mut dyn FnMut(&mut Node)) {{
        match self {{
{walk_mut_arms}            _ => {{}}
        }}
    }}
}}
"
    );
}

// ---------------------------------------------------------------- tables

fn arr<'a>(v: &'a Value, key: &str) -> &'a [Value] {
    v.get(key).and_then(Value::as_array).map_or(&[], Vec::as_slice)
}

fn s<'a>(v: &'a Value, key: &str) -> &'a str {
    v.get(key).and_then(Value::as_str).unwrap_or("")
}

fn code_point(text: &str) -> char {
    let hex = text.trim_start_matches("U+");
    u32::from_str_radix(hex, 16).ok().and_then(char::from_u32).unwrap_or('\u{FFFD}')
}

fn gen_tables(dir: &Path) -> String {
    let mut out = String::from("// @generated by build.rs from spec-data/*.json.\n\n");
    gen_limits(&mut out, &load(dir, "limits.json"));
    gen_tasks(&mut out, &load(dir, "task-states.json"));
    gen_divs(&mut out, &load(dir, "div-names.json"));
    gen_smart(&mut out, &load(dir, "smart-punctuation.json"));
    gen_slug(&mut out, &load(dir, "heading-slug.json"));
    gen_url(&mut out, &load(dir, "url-policy.json"));
    gen_options(&mut out, &load(dir, "options.json"));
    gen_delims(&mut out, &load(dir, "inline-delimiters.json"), &load(dir, "inline-braces.json"));
    gen_includes(&mut out, &load(dir, "include-options.json"));
    gen_dispatch(&mut out, &load(dir, "line-shapes.json"));
    out
}

fn gen_limits(out: &mut String, v: &Value) {
    for row in arr(v, "limits") {
        let name = s(row, "name").to_ascii_uppercase();
        let value = row.get("value").and_then(Value::as_u64).unwrap_or(0);
        let _ = writeln!(out, "pub const {name}: usize = {value};");
    }
    out.push('\n');
}

fn gen_tasks(out: &mut String, v: &Value) {
    out.push_str("/// (box character, tree mark, `data-task-state` value, checked)\npub const TASK_STATES: &[(char, char, Option<char>, bool)] = &[\n");
    for row in arr(v, "states") {
        let c = s(row, "char").chars().next().unwrap_or(' ');
        let m = s(row, "mark").chars().next().unwrap_or(' ');
        let attr = row.get("state_attribute").and_then(Value::as_str).and_then(|a| a.chars().next());
        let checked = row.get("checked").and_then(Value::as_bool).unwrap_or(false);
        let _ = writeln!(out, "    ({c:?}, {m:?}, {attr:?}, {checked}),");
    }
    out.push_str("];\n\n");
}

fn gen_divs(out: &mut String, v: &Value) {
    out.push_str("/// (div name, kind: `admonition`, `directive` or `figure_group`)\npub const DIV_NAMES: &[(&str, &str)] = &[\n");
    for row in arr(v, "names") {
        let _ = writeln!(out, "    ({:?}, {:?}),", s(row, "name"), s(row, "kind"));
    }
    out.push_str("];\n\n/// (sigil, container name, class)\npub const DIV_SIGILS: &[(char, &str, &str)] = &[\n");
    for row in arr(v, "sigils") {
        let c = s(row, "sigil").chars().next().unwrap_or(' ');
        let _ = writeln!(out, "    ({c:?}, {:?}, {:?}),", s(row, "name"), s(row, "class"));
    }
    out.push_str("];\n\n");
}

fn gen_smart(out: &mut String, v: &Value) {
    out.push_str("/// (source run, replaced, kind, glyph)\npub const SMART_RUNS: &[(&str, bool, &str, &str)] = &[\n");
    for row in arr(v, "runs") {
        let replaced = row.get("replaced").and_then(Value::as_bool).unwrap_or(false);
        let _ = writeln!(out, "    ({:?}, {replaced}, {:?}, {:?}),", s(row, "source"), s(row, "kind"), s(row, "glyph"));
    }
    out.push_str("];\n\n/// (kind, source, glyph)\npub const SMART_QUOTES: &[(&str, &str, &str)] = &[\n");
    for row in arr(v, "quotes") {
        let _ = writeln!(out, "    ({:?}, {:?}, {:?}),", s(row, "kind"), s(row, "source"), s(row, "glyph"));
    }
    out.push_str("];\n\n/// (kind, source, glyph)\npub const SMART_DASHES: &[(&str, &str, &str)] = &[\n");
    for row in arr(v, "dashes") {
        let _ = writeln!(out, "    ({:?}, {:?}, {:?}),", s(row, "kind"), s(row, "source"), s(row, "glyph"));
    }
    out.push_str("];\n\n");
    let opens = v.get("quote_opens_after").cloned().unwrap_or(Value::Null);
    let chars: String = arr(&opens, "chars").iter().filter_map(Value::as_str).collect();
    let _ = writeln!(out, "pub const QUOTE_OPENS_AFTER_CHARS: &str = {chars:?};");
    let closes = v.get("quote_closes_after_hyphen_dash_or_slash_before").cloned().unwrap_or(Value::Null);
    let chars: String = arr(&closes, "chars").iter().filter_map(Value::as_str).collect();
    let _ = writeln!(out, "pub const QUOTE_CLOSES_AFTER_DASH_BEFORE_CHARS: &str = {chars:?};");
    let words = v.get("apostrophe_words").cloned().unwrap_or(Value::Null);
    let list: Vec<String> = arr(&words, "words").iter().filter_map(Value::as_str).map(|w| format!("{w:?}")).collect();
    let _ = writeln!(out, "pub const APOSTROPHE_WORDS: &[&str] = &[{}];\n", list.join(", "));
}

fn gen_slug(out: &mut String, v: &Value) {
    let removed: Vec<String> = arr(v, "removed").iter().map(|r| format!("{:?}", code_point(s(r, "code_point")))).collect();
    let _ = writeln!(out, "pub const SLUG_REMOVED: &[char] = &[{}];", removed.join(", "));
    out.push_str("pub const SLUG_REVERSED: &[(char, &str)] = &[\n");
    for row in arr(v, "reversed") {
        let g = s(row, "glyph").chars().next().unwrap_or(' ');
        let _ = writeln!(out, "    ({g:?}, {:?}),", s(row, "ascii"));
    }
    out.push_str("];\n\n");
}

fn gen_url(out: &mut String, v: &Value) {
    out.push_str("/// Inclusive code point ranges the scheme probe removes (C2-H-159).\npub const PROBE_REMOVES: &[(char, char)] = &[\n");
    for row in arr(v, "probe_removes") {
        let _ = writeln!(out, "    ({:?}, {:?}),", code_point(s(row, "from")), code_point(s(row, "to")));
    }
    out.push_str("];\n\n/// (name, `name` or `prefix`)\npub const DROPPED_ATTRIBUTES: &[(&str, &str)] = &[\n");
    for row in arr(v, "dropped_attributes") {
        let _ = writeln!(out, "    ({:?}, {:?}),", s(row, "name"), s(row, "match"));
    }
    out.push_str("];\n\n/// (attribute, splits at commas too)\npub const URL_LIST_ATTRIBUTES: &[(&str, bool)] = &[\n");
    for row in arr(v, "url_list_attributes") {
        let comma = arr(row, "separators").iter().any(|x| x.as_str() == Some("comma"));
        let _ = writeln!(out, "    ({:?}, {comma}),", s(row, "name"));
    }
    out.push_str("];\n\n");
    let pats: Vec<String> = arr(v, "style_patterns").iter().map(|r| format!("{:?}", s(r, "text"))).collect();
    let _ = writeln!(out, "pub const STYLE_PATTERNS: &[&str] = &[{}];\n", pats.join(", "));
    out.push_str("pub struct ProfileRow {\n    pub name: &'static str,\n    pub denied_block: &'static [&'static str],\n    pub denied_inline: &'static [&'static str],\n    pub allowed_block: Option<&'static [&'static str]>,\n    pub allowed_inline: Option<&'static [&'static str]>,\n    pub link_rel: &'static [&'static str],\n    pub max_nesting: Option<usize>,\n    pub max_length: Option<usize>,\n}\n\npub const PROFILES: &[ProfileRow] = &[\n");
    for row in arr(v, "profiles") {
        let list = |k: &str| arr(row, k).iter().filter_map(Value::as_str).map(|x| format!("{x:?}")).collect::<Vec<_>>().join(", ");
        let opt = |k: &str| if row.get(k).is_some() { format!("Some(&[{}])", list(k)) } else { "None".into() };
        let num = |k: &str| row.get(k).and_then(Value::as_u64).map_or("None".into(), |n| format!("Some({n})"));
        let _ = writeln!(
            out,
            "    ProfileRow {{ name: {:?}, denied_block: &[{}], denied_inline: &[{}], allowed_block: {}, allowed_inline: {}, link_rel: &[{}], max_nesting: {}, max_length: {} }},",
            s(row, "name"),
            list("denied_block"),
            list("denied_inline"),
            opt("allowed_block"),
            opt("allowed_inline"),
            list("link_rel"),
            num("max_nesting"),
            num("max_length")
        );
    }
    out.push_str("];\n\n");
}

fn gen_options(out: &mut String, v: &Value) {
    for row in arr(v, "options") {
        let name = s(row, "name");
        let default = row.get("default").cloned().unwrap_or(Value::Null);
        match name {
            "labels" => {
                out.push_str("pub const DEFAULT_LABELS: &[(&str, &str)] = &[\n");
                for (k, val) in default.as_object().into_iter().flatten() {
                    let _ = writeln!(out, "    ({k:?}, {:?}),", val.as_str().unwrap_or(""));
                }
                out.push_str("];\n");
            }
            "urlPolicy" => {
                let deny: Vec<String> = arr(&default, "deny").iter().filter_map(Value::as_str).map(|x| format!("{x:?}")).collect();
                let _ = writeln!(out, "pub const DEFAULT_DENIED_SCHEMES: &[&str] = &[{}];", deny.join(", "));
            }
            _ => {
                if let Some(b) = default.as_bool() {
                    let _ = writeln!(out, "pub const DEFAULT_{}: bool = {b};", snake(name).to_ascii_uppercase());
                } else if let Some(t) = default.as_str() {
                    let _ = writeln!(out, "pub const DEFAULT_{}: &str = {t:?};", snake(name).to_ascii_uppercase());
                }
            }
        }
    }
    out.push('\n');
}

fn gen_delims(out: &mut String, v: &Value, braces: &Value) {
    out.push_str("/// (mark, node type, form `bare` or `braced`)\npub const DELIMITERS: &[(char, &str, &str)] = &[\n");
    for row in arr(v, "delimiters") {
        let c = s(row, "mark").chars().next().unwrap_or(' ');
        let _ = writeln!(out, "    ({c:?}, {:?}, {:?}),", s(row, "node"), s(row, "form"));
    }
    out.push_str("];\n");
    let marks: String = arr(braces, "order")
        .iter()
        .filter(|r| s(r, "name") == "braced_opener")
        .flat_map(|r| arr(r, "marks").iter().filter_map(Value::as_str))
        .collect();
    let _ = writeln!(out, "pub const BRACED_MARKS: &str = {marks:?};\n");
}

fn gen_includes(out: &mut String, v: &Value) {
    out.push_str("/// (rank, key, value shape, without value, outside shape, repeated)\npub const INCLUDE_OPTIONS: &[(u64, &str, &str, &str, &str, &str)] = &[\n");
    for row in arr(v, "options") {
        let rank = row.get("rank").and_then(Value::as_u64).unwrap_or(0);
        let _ = writeln!(
            out,
            "    ({rank}, {:?}, {:?}, {:?}, {:?}, {:?}),",
            s(row, "name"),
            s(row, "value"),
            s(row, "without_value"),
            s(row, "outside_shape"),
            s(row, "repeated")
        );
    }
    out.push_str("];\n\n");
}

/// The dispatch of the block pass: for each ASCII character, the line shapes
/// that may start with it (`name` and `first` of line-shapes.json).
fn gen_dispatch(out: &mut String, v: &Value) {
    let mut table: Vec<Vec<String>> = vec![Vec::new(); 128];
    for shape in arr(v, "shapes") {
        let name = s(shape, "name");
        for first in arr(shape, "first").iter().filter_map(Value::as_str) {
            let b = first.as_bytes();
            let (lo, hi) = if b.len() == 3 && b[1] == b'-' { (b[0], b[2]) } else { (b[0], b[0]) };
            for c in lo..=hi {
                table[usize::from(c)].push(name.to_string());
            }
        }
    }
    out.push_str("/// Line shapes by first character (line-shapes.json `first`).\npub const SHAPES_BY_FIRST: [&[&str]; 128] = [\n");
    for row in &table {
        let names: Vec<String> = row.iter().map(|n| format!("{n:?}")).collect();
        let _ = writeln!(out, "    &[{}],", names.join(", "));
    }
    out.push_str("];\n");
}
